import { DEFAULT_LOCALE, FAMILY_TIMEZONE, LOCALES, type ErrorCode, type Locale } from '@ruya/shared';

export const LOCALE_COOKIE = 'ruya_lang';

export function isLocale(value: string | undefined): value is Locale {
  return LOCALES.includes(value as Locale);
}

export function resolveLocale(value: string | undefined): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

/** Quick encouragement phrases (US-15). Each has an icon in the UI; the text is sent as-is. */
export type EncouragementId = 'great' | 'proud' | 'love' | 'luck';

export const dir = (locale: Locale) => (locale === 'ar' ? 'rtl' : 'ltr');

/** US-16: dates and numbers follow the chosen language. */
export function formatDate(isoDate: string, locale: Locale) {
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-EG' : 'en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${isoDate}T00:00:00Z`));
}

export function formatNumber(n: number, locale: Locale) {
  return new Intl.NumberFormat(locale === 'ar' ? 'ar-EG' : 'en-US').format(n);
}

/** A moment shown on the family's clock, e.g. "٨:١٥ ص". */
export function formatClock(iso: string, locale: Locale) {
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-EG' : 'en-US', {
    hour: 'numeric',
    minute: '2-digit',
    timeZone: FAMILY_TIMEZONE,
  }).format(new Date(iso));
}

/** A moment with its date, on the family's clock: "٢٨ أكتوبر، ٨:١٥ م". */
export function formatDateTime(iso: string, locale: Locale) {
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-EG' : 'en-GB', {
    day: 'numeric',
    month: 'short',
    hour: 'numeric',
    minute: '2-digit',
    timeZone: FAMILY_TIMEZONE,
  }).format(new Date(iso));
}

/** A date split for a calendar-style tile: day number, short month, weekday. */
export function formatDateParts(isoDate: string, locale: Locale) {
  const date = new Date(`${isoDate}T00:00:00Z`);
  const tag = locale === 'ar' ? 'ar-EG' : 'en-GB';
  const part = (options: Intl.DateTimeFormatOptions) =>
    new Intl.DateTimeFormat(tag, { ...options, timeZone: 'UTC' }).format(date);
  return { day: part({ day: 'numeric' }), month: part({ month: 'short' }), weekday: part({ weekday: 'long' }) };
}

/** "الأربع، ٢٨ أكتوبر" / "Wednesday, 28 October". */
export function formatDayLong(isoDate: string, locale: Locale) {
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-EG' : 'en-GB', {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
    timeZone: 'UTC',
  }).format(new Date(`${isoDate}T00:00:00Z`));
}

/** "17:30" → "٥:٣٠ م" / "5:30 PM". */
export function formatTime(hhmm: string, locale: Locale) {
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-EG' : 'en-US', {
    hour: 'numeric',
    minute: '2-digit',
    timeZone: 'UTC',
  }).format(new Date(`1970-01-01T${hhmm}:00Z`));
}

/** Arabic counts change form with the number: سنة، سنتين، ٣ سنين، ١١ سنة. */
function arabicYears(n: number) {
  const digits = formatNumber(n, 'ar');
  switch (new Intl.PluralRules('ar').select(n)) {
    case 'one':
      return 'سنة';
    case 'two':
      return 'سنتين';
    case 'few':
      return `${digits} سنين`;
    default:
      return `${digits} سنة`;
  }
}

